bool IsSafeRelativeDumpName(const FString& Name)
{
    if (Name.IsEmpty()
        || Name.Contains(TEXT(":"))
        || Name.StartsWith(TEXT("/"))
        || Name.StartsWith(TEXT("\\"))
        || Name.Contains(TEXT("..")))
    {
        return false;
    }
    return true;
}

bool TryResolveDumpFilePath(const FString& AbsDir, const FString& Name, FString& OutPath)
{
    if (!IsSafeRelativeDumpName(Name))
    {
        return false;
    }

    OutPath = FPaths::ConvertRelativePathToFull(AbsDir / Name);
    FPaths::NormalizeFilename(OutPath);
    return OutPath.StartsWith(AbsDir + TEXT("/"));
}

FString MakeDumpPathKey(const FString& Path)
{
    FString Key = Path;
    FPaths::NormalizeFilename(Key);
#if PLATFORM_WINDOWS
    Key.ToLowerInline();
#endif
    return Key;
}

TArray<uint8> EncodeUtf8(const FString& Content)
{
    FTCHARToUTF8 Converted(*Content, Content.Len());
    TArray<uint8> Bytes;
    Bytes.Append(reinterpret_cast<const uint8*>(Converted.Get()), Converted.Length());
    return Bytes;
}

FString StripTrailingLineWhitespace(const FString& Content)
{
    FString Result;
    Result.Reserve(Content.Len());
    for (const TCHAR Character : Content)
    {
        if (Character == TEXT('\r') || Character == TEXT('\n'))
        {
            while (!Result.IsEmpty()
                && (Result[Result.Len() - 1] == TEXT(' ')
                    || Result[Result.Len() - 1] == TEXT('\t')))
            {
                Result.LeftChopInline(1, EAllowShrinking::No);
            }
        }
        Result.AppendChar(Character);
    }
    while (!Result.IsEmpty()
        && (Result[Result.Len() - 1] == TEXT(' ')
            || Result[Result.Len() - 1] == TEXT('\t')))
    {
        Result.LeftChopInline(1, EAllowShrinking::No);
    }
    return Result;
}

struct FPreparedDumpFile
{
    FString Name;
    FString FinalPath;
    FString StagedPath;
    FString BackupPath;
    TArray<uint8> Bytes;
    bool bChanged = false;
    bool bHadPrevious = false;
};

struct FMovedStaleFile
{
    FString OriginalPath;
    FString BackupPath;
};

void AddWriteError(
    FWriteResult& Result,
    const FString& Name,
    const FString& Message,
    FString& OutError)
{
    Result.Errors.Add(TPair<FString, FString>(Name, Message));
    if (OutError.IsEmpty())
    {
        OutError = Message;
    }
}

void CleanupTransactionDirectory(const FString& Path)
{
    if (!Path.IsEmpty()
        && IFileManager::Get().DirectoryExists(*Path)
        && !IFileManager::Get().DeleteDirectory(*Path, /*RequireExists=*/false, /*Tree=*/true))
    {
        UE_LOG(LogPinWrightSubsystem, Warning,
            TEXT("Asset dump writer could not remove transaction directory: %s"), *Path);
    }
}

bool TryMakeRelativeSiblingPath(
    const FString& AbsDir,
    const FString& Name,
    const FString& Suffix,
    const FString& Extension,
    FString& OutPath)
{
    if (!IsSafeRelativeDumpName(Name))
    {
        return false;
    }

    const FString RelativeDir = FPaths::GetPath(Name);
    const FString Stem = FPaths::GetBaseFilename(Name, /*bRemovePath=*/true);
    const FString FileName = Stem + Suffix + Extension;
    OutPath = RelativeDir.IsEmpty() ? AbsDir / FileName : AbsDir / RelativeDir / FileName;
    OutPath = FPaths::ConvertRelativePathToFull(OutPath);
    FPaths::NormalizeFilename(OutPath);
    return OutPath.StartsWith(AbsDir + TEXT("/"));
}

bool WriteFileAtomic(const FString& FinalPath, const FString& Content,
                     TArray<FString>& WrittenPaths,
                     TArray<TPair<FString, FString>>& Errors,
                     const FString& Name)
{
    IFileManager& FM = IFileManager::Get();
    FM.MakeDirectory(*FPaths::GetPath(FinalPath), /*Tree=*/true);
    FString TmpPath = FinalPath + TEXT(".tmp");

    bool bSaved = FFileHelper::SaveStringToFile(
        StripTrailingLineWhitespace(Content), *TmpPath,
        FFileHelper::EEncodingOptions::ForceUTF8WithoutBOM);
    if (!bSaved)
    {
        FM.Delete(*TmpPath, /*RequireExists=*/false);
        Errors.Add(TPair<FString, FString>(Name,
            FString::Printf(TEXT("Failed to write tmp file: %s"), *TmpPath)));
        return false;
    }

    bool bMoved = FM.Move(*FinalPath, *TmpPath, /*bReplace=*/true, /*bEvenReadOnly=*/false);
    if (!bMoved)
    {
        FM.Delete(*TmpPath, /*RequireExists=*/false);
        Errors.Add(TPair<FString, FString>(Name,
            FString::Printf(TEXT("Failed to rename tmp to final: %s"), *FinalPath)));
        return false;
    }

    WrittenPaths.Add(FinalPath);
    return true;
}

